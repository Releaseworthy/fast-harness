//! Golden output of the generator for zero, one and two plugins, and the
//! checks of `plugins.toml` and the dependency markers.

use super::gen::{check_deps, generate, parse};

const HEAD: &str = "// Generated by build.rs from plugins.toml (docs/plugins.md): do not edit.\n\n";
const DOC: &str = "/// Calls `register` of every plugin, in `plugins.toml` order.\n";

#[test]
fn zero_plugins_generate_an_empty_register_all() {
    let plugins = parse("# nothing yet\n\n").unwrap();
    assert!(plugins.is_empty());
    let expected = format!(
        "{HEAD}/// The plugins of this build, in `plugins.toml` order.\npub const PLUGINS: &[&str] = &[];\n\n{DOC}pub fn register_all(_ext: &mut fast_harness_core::ext::v1::Ext) {{}}\n"
    );
    assert_eq!(generate(&plugins), expected);
}

#[test]
fn one_plugin() {
    let text = "[[plugin]]\nname = \"hello-tool\" # the crate\ngit = \"https://github.com/me/hello-tool\"\nrev = \"0123abcd\"\n";
    let plugins = parse(text).unwrap();
    assert_eq!(plugins[0].rev.as_deref(), Some("0123abcd"));
    let expected = format!(
        "{HEAD}/// The plugins of this build, in `plugins.toml` order.\npub const PLUGINS: &[&str] = &[\"hello-tool\"];\n\n{DOC}pub fn register_all(ext: &mut fast_harness_core::ext::v1::Ext) {{\n    ::hello_tool::register(ext);\n}}\n"
    );
    assert_eq!(generate(&plugins), expected);
}

#[test]
fn two_plugins_keep_file_order() {
    let text = "[[plugin]]\nname = \"zeta\"\npath = \"plugins/zeta\"\n\n[[plugin]]\nname = \"alpha_panel\"\ngit = \"https://example.com/a.git\"\nrev = \"v1.2.0\"\n";
    let plugins = parse(text).unwrap();
    let expected = format!(
        "{HEAD}/// The plugins of this build, in `plugins.toml` order.\npub const PLUGINS: &[&str] = &[\"zeta\", \"alpha_panel\"];\n\n{DOC}pub fn register_all(ext: &mut fast_harness_core::ext::v1::Ext) {{\n    ::zeta::register(ext);\n    ::alpha_panel::register(ext);\n}}\n"
    );
    assert_eq!(generate(&plugins), expected);
}

#[test]
fn bad_lists_name_the_line_or_plugin() {
    let err = |text: &str| parse(text).unwrap_err();
    assert!(err("name = \"x\"").contains("line 1"));
    assert!(err("[[plugin]]\nname = \"x\"\ngit = \"u\"").contains("needs `rev`"));
    assert!(err("[[plugin]]\nname = \"x\"\nbranch = \"main\"").contains("unknown key"));
    assert!(err("[[plugin]]\nname = \"x\"").contains("exactly one"));
    assert!(err("[[plugin]]\nname = \"x y\"\npath = \"p\"").contains("letters"));
    let twice =
        "[[plugin]]\nname = \"a-b\"\npath = \"p\"\n[[plugin]]\nname = \"a_b\"\npath = \"q\"";
    assert!(err(twice).contains("twice"));
    assert!(err("[[plugin]]\nname = 'x'").contains("quoted"));
}

#[test]
fn api_key_is_checked_against_the_supported_version() {
    let entry = |api: &str| format!("[[plugin]]\nname = \"x\"\npath = \"p\"\n{api}");
    assert_eq!(parse(&entry("")).unwrap()[0].api, None);
    assert_eq!(parse(&entry("api = 1")).unwrap()[0].api, Some(1));
    assert_eq!(
        parse(&entry("api = \"1\" # quoted")).unwrap()[0].api,
        Some(1)
    );
    let err = parse(&entry("api = 2")).unwrap_err();
    assert!(
        err.contains("plugin `x` targets plugin API 2") && err.contains("supports API 1"),
        "{err}"
    );
    assert!(parse(&entry("api = one"))
        .unwrap_err()
        .contains("whole number"));
}

/// The plugin API number has three copies: the core's, `gen::API` (the
/// build script cannot use the core) and `scripts/apply-plugins.ts`.
#[test]
fn api_version_copies_agree() {
    assert_eq!(super::gen::API, fast_harness_core::ext::API_VERSION);
    let script = include_str!("../../../scripts/apply-plugins.ts");
    let line = format!(
        "const API_VERSION = {};",
        fast_harness_core::ext::API_VERSION
    );
    assert!(
        script.contains(&line),
        "scripts/apply-plugins.ts lacks `{line}`"
    );
}

#[test]
fn deps_between_markers_must_match_the_list() {
    let plugins = parse("[[plugin]]\nname = \"one\"\npath = \"p\"\n").unwrap();
    let with = "[dependencies]\n# BEGIN PLUGINS\none = { path = \"../../p\" }\n# END PLUGINS\n";
    let without = "[dependencies]\n# BEGIN PLUGINS\n# END PLUGINS\n";
    assert!(check_deps(with, &plugins).is_ok());
    assert!(check_deps(without, &[]).is_ok());
    assert!(check_deps(without, &plugins)
        .unwrap_err()
        .contains("apply-plugins"));
    assert!(check_deps("[dependencies]\n", &[]).is_err());
}

#[test]
fn install_reports_whether_the_list_has_plugins() {
    // Official builds have an empty list; a custom build (build-custom.yml) has its own.
    assert_eq!(super::install(), !super::PLUGINS.is_empty());
}
